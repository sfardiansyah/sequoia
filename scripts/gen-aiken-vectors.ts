import { readFileSync, writeFileSync } from "node:fs";

type SplitCase = {
  amount: number;
  memberCapitalBps: number;
  capitalParticipationBps: number;
  memberCapital: number;
  capitalParticipation: number;
};

type VestingCase = {
  months: number;
  vestedBps: number;
};

type LeafCase = { secret: string; leaf: string };
type NullifierCase = { secret: string; proposalId: string; nullifier: string };
type CommitmentCase = { choice: number; salt: string; commitment: string };
type WindowCase = {
  start: number;
  votingDays: number;
  revealDays: number;
  timelockDays: number;
  end: number;
  revealEnd: number;
  finalizedAt: number;
  timelockEnd: number;
};
type QuorumCase = {
  votes: number;
  eligibleCount: number;
  quorumBps: number;
  met: boolean;
};
type ThresholdCase = {
  yes: number;
  no: number;
  thresholdBps: number;
  met: boolean;
};

type GovernanceVectors = {
  leaf: LeafCase[];
  nullifier: NullifierCase[];
  commitment: CommitmentCase[];
  windows: WindowCase[];
  quorum: QuorumCase[];
  threshold: ThresholdCase[];
};

const aiken = JSON.parse(
  readFileSync("packages/shared/vectors/aiken.json", "utf8"),
) as { split: SplitCase[]; vesting: VestingCase[] };
const governance = JSON.parse(
  readFileSync("packages/shared/vectors/governance.json", "utf8"),
) as GovernanceVectors;

function assertSafeIntegers(vector: object): void {
  for (const [name, value] of Object.entries(vector)) {
    if (typeof value !== "number" || !Number.isSafeInteger(value)) {
      throw new Error(`Vector ${name} must be a safe integer, got ${String(value)}`);
    }
  }
}

for (const vector of [...aiken.split, ...aiken.vesting]) {
  assertSafeIntegers(vector);
}

const hexLiteral = (value: string): string => {
  if (!/^[0-9a-f]{64}$/.test(value)) {
    throw new Error(`Expected a 32-byte lower-case hex string, got ${value}`);
  }
  return `#"${value}"`;
};

const intLiteral = (value: number): string => {
  if (!Number.isSafeInteger(value)) {
    throw new Error(`Expected a safe integer, got ${String(value)}`);
  }
  return String(value);
};

const boolLiteral = (value: boolean): string => (value ? "True" : "False");

const splitLines = [
  "// Generated by scripts/gen-aiken-vectors.ts from packages/shared/vectors/aiken.json.",
  "// Do not edit by hand; run `bun run gen:vectors`.",
  "// split_cases: (amount, member_capital_bps, capital_participation_bps, member_capital, capital_participation)",
  "// vesting_cases: (months_since_join, vested_bps)",
  "",
  "pub const split_cases: List<(Int, Int, Int, Int, Int)> = [",
  ...aiken.split.map(
    (c) =>
      `  (${intLiteral(c.amount)}, ${intLiteral(c.memberCapitalBps)}, ${intLiteral(c.capitalParticipationBps)}, ${intLiteral(c.memberCapital)}, ${intLiteral(c.capitalParticipation)}),`,
  ),
  "]",
  "",
  "pub const vesting_cases: List<(Int, Int)> = [",
  ...aiken.vesting.map((c) => `  (${intLiteral(c.months)}, ${intLiteral(c.vestedBps)}),`),
  "]",
  "",
];

const votingLines = [
  "// Generated by scripts/gen-aiken-vectors.ts from packages/shared/vectors/governance.json.",
  "// Do not edit by hand; run `bun run gen:vectors`.",
  "// leaf_cases: (vote_secret, leaf)",
  "// nullifier_cases: (vote_secret, proposal_id, nullifier)",
  "// commitment_cases: (choice_index, reveal_salt, commitment)",
  "// window_cases: (start, voting_days, reveal_days, timelock_days, end, reveal_end, finalized_at, timelock_end)",
  "// quorum_cases: (votes, eligible_count, quorum_bps, met)",
  "// threshold_cases: (yes, no, threshold_bps, met)",
  "",
  "pub const leaf_cases: List<(ByteArray, ByteArray)> = [",
  ...governance.leaf.map(
    (c) => `  (${hexLiteral(c.secret)}, ${hexLiteral(c.leaf)}),`,
  ),
  "]",
  "",
  "pub const nullifier_cases: List<(ByteArray, ByteArray, ByteArray)> = [",
  ...governance.nullifier.map(
    (c) =>
      `  (${hexLiteral(c.secret)}, ${hexLiteral(c.proposalId)}, ${hexLiteral(c.nullifier)}),`,
  ),
  "]",
  "",
  "pub const commitment_cases: List<(Int, ByteArray, ByteArray)> = [",
  ...governance.commitment.map(
    (c) =>
      `  (${intLiteral(c.choice)}, ${hexLiteral(c.salt)}, ${hexLiteral(c.commitment)}),`,
  ),
  "]",
  "",
  "pub const window_cases: List<(Int, Int, Int, Int, Int, Int, Int, Int)> = [",
  ...governance.windows.map(
    (c) =>
      `  (${intLiteral(c.start)}, ${intLiteral(c.votingDays)}, ${intLiteral(c.revealDays)}, ${intLiteral(c.timelockDays)}, ${intLiteral(c.end)}, ${intLiteral(c.revealEnd)}, ${intLiteral(c.finalizedAt)}, ${intLiteral(c.timelockEnd)}),`,
  ),
  "]",
  "",
  "pub const quorum_cases: List<(Int, Int, Int, Bool)> = [",
  ...governance.quorum.map(
    (c) =>
      `  (${intLiteral(c.votes)}, ${intLiteral(c.eligibleCount)}, ${intLiteral(c.quorumBps)}, ${boolLiteral(c.met)}),`,
  ),
  "]",
  "",
  "pub const threshold_cases: List<(Int, Int, Int, Bool)> = [",
  ...governance.threshold.map(
    (c) =>
      `  (${intLiteral(c.yes)}, ${intLiteral(c.no)}, ${intLiteral(c.thresholdBps)}, ${boolLiteral(c.met)}),`,
  ),
  "]",
  "",
];

writeFileSync("contracts/lib/sequoia/vectors.ak", splitLines.join("\n"));
writeFileSync("contracts/lib/sequoia/voting_vectors.ak", votingLines.join("\n"));
